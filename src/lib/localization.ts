export function translateText(text: string, language: LanguageCode): string {
  const translated =
    translations[language]?.[text] ??
    additionalTranslations[language]?.[text] ??
    pageTranslations[language]?.[text] ??
    interfaceTranslations[language]?.[text];
  if (translated !== undefined) return translated;

  if (language === "en") return text;
  const dynamicMatch = text.match(/^Add (.+) to cart$/);
  if (dynamicMatch) {
    return `${translateText("Add ", language)}${dynamicMatch[1]}${translateText(" to cart", language)}`;
  }
  const cartMatch = text.match(/^Cart, (\d+) items$/);
  if (cartMatch) {
    return `${translateText("Cart, ", language)}${cartMatch[1]}${translateText(" items", language)}`;
  }
  const shoppingCartMatch = text.match(/^Shopping Cart \((\d+)\)$/);
  if (shoppingCartMatch) {
    return `${translateText("Shopping Cart", language)} (${shoppingCartMatch[1]})`;
  }
  const packagingMatch = text.match(/^Packaging for (.+)$/);
  if (packagingMatch) {
    return `${translateText("Packaging", language)} ${packagingMatch[1]}`;
  }
  const recipeMatch = text.match(/^View (.+) recipe$/);
  if (recipeMatch) {
    return `${translateText("View recipe", language)}: ${translateText(recipeMatch[1], language)}`;
  }
  const starsMatch = text.match(/^(\d+) out of 5 stars$/);
  if (starsMatch) {
    return `${starsMatch[1]} ${translateText("out of 5 stars", language)}`;
  }
  return text;
}
